"""Materialises the pinned iw4L crates CODV compiles into build/overlay/iw4l
and applies CODV's own patches from patches/iw4l/*.patch in name order, the
way SK8V builds its Skate overlay. upstream/ stays untouched; the runtime's
crates depend on the overlay by path.

    python tools/prepare_overlay.py [--force] [--source <iw4L checkout>]

Only the crates listed in CRATES are copied, under a generated workspace
manifest (edition, licence and lints from iw4L's own), so the build never
touches iw4L's renderer, networking or Bevy dependencies.
"""
import argparse
import hashlib
import os
import re
import shutil
import subprocess
import sys
import uuid
from pathlib import Path

from _common import REPO, lock

# What CodVRuntime.dll compiles from iw4L, dependencies first.
CRATES = ['math_iw4', 'playerstate_iw4', 'trace_iw4', 'movement_iw4', 'd3d9_decl', 'd3d9_state', 'asset_iw4',
          'weapon_iw4', 'clipmap_iw4', 'fastfile_iw4', 'anim_iw4', 'xmodel_runtime', 'hud_iw4']
# Third-party crates those depend on through iw4L's [workspace.dependencies]
# (copied from iw4L's manifest with their pinned versions).
EXTERNAL = ['glam']
PATCHES = REPO / 'patches/iw4l'
DEST = REPO / 'build/overlay/iw4l'
STAMP = '.codv-overlay'


def section(text, name):
    """The body of a [name] table in a TOML file (up to the next table header)."""
    m = re.search(rf'^\[{re.escape(name)}\]\s*\n(.*?)(?=^\[|\Z)', text, re.M | re.S)
    lines = m.group(1).strip().splitlines() if m else []
    # Comments that follow the last key belong to the next table, not this one.
    while lines and (not lines[-1].strip() or lines[-1].lstrip().startswith('#')):
        lines.pop()
    return '\n'.join(lines)


def manifest(upstream_root):
    text = upstream_root.read_text(encoding='utf-8')
    members = ',\n'.join(f'    "crates/{c}"' for c in CRATES)
    deps = '\n'.join(f'{c} = {{ path = "crates/{c}" }}' for c in CRATES)
    upstream_deps = section(text, 'workspace.dependencies').splitlines()
    for name in EXTERNAL:
        line = next((l for l in upstream_deps if re.match(rf'{re.escape(name)}\s*=', l.strip())), None)
        if line is None:
            raise SystemExit(f'iw4L manifest has no workspace dependency {name}')
        deps += '\n' + line.strip()
    parts = [
        '# Generated by CODV tools/prepare_overlay.py from the pinned iw4L checkout. Do not edit;',
        '# change CODV through patches/iw4l/*.patch instead.',
        '[workspace]', 'resolver = "3"', f'members = [\n{members},\n]', '',
        '[workspace.package]', section(text, 'workspace.package'), '',
        '[workspace.dependencies]', deps, '',
    ]
    for lints in ('workspace.lints.rust', 'workspace.lints.clippy'):
        body = section(text, lints)
        if body:
            parts += [f'[{lints}]', body, '']
    return '\n'.join(parts)


def key(commit, patches):
    h = hashlib.sha256()
    h.update(commit.encode())
    h.update(Path(__file__).read_bytes())
    for p in patches:
        h.update(p.name.encode())
        h.update(p.read_bytes())
    return h.hexdigest()


def head(path):
    r = subprocess.run(['git', '-C', str(path), 'rev-parse', 'HEAD'], capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else ''


def main():
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument('--force', action='store_true')
    p.add_argument('--source', type=Path, help='iw4L checkout (default upstream/iw4L, verified against the lock)')
    p.add_argument('--dest', type=Path, default=DEST)
    a = p.parse_args()
    pinned = lock('iw4L')['commit']
    source = a.source or REPO / 'upstream/iw4L'
    if not (source / 'Cargo.toml').is_file():
        raise SystemExit(f'{source} has no iw4L checkout: run tools/fetch-upstreams.ps1 (or BOOTSTRAP.bat) first')
    commit = head(source) or pinned
    if commit != pinned:
        raise SystemExit(f'{source} is at {commit}, upstreams.lock.json pins {pinned}')
    patches = sorted(PATCHES.glob('*.patch'))
    k = key(commit, patches)
    stamp = a.dest / STAMP
    if not a.force and stamp.is_file() and stamp.read_text().strip() == k:
        print(f'iw4L overlay up to date ({len(patches)} patches)')
        return 0
    # Build in a sibling first: a failed patch never destroys a working overlay.
    a.dest.parent.mkdir(parents=True, exist_ok=True)
    stage = a.dest.parent / f'iw4l-stage-{uuid.uuid4().hex}'
    stage.mkdir()
    for c in CRATES:
        src = source / 'crates' / c
        if not (src / 'Cargo.toml').is_file():
            raise SystemExit(f'iw4L at {commit} has no crates/{c}')
        shutil.copytree(src, stage / 'crates' / c, ignore=shutil.ignore_patterns('target'))
    (stage / 'Cargo.toml').write_text(manifest(source / 'Cargo.toml'), encoding='utf-8')
    for name in ('LICENSE', 'NOTICE'):
        if (source / name).is_file():
            shutil.copyfile(source / name, stage / name)
    # The stage sits inside the CODV checkout: keep git from finding the outer
    # repository (its attributes would rewrite line endings and break patches).
    env = dict(os.environ, GIT_CEILING_DIRECTORIES=str(a.dest.parent.resolve()))
    for patch in patches:
        print(f'PATCH {patch.name}', flush=True)
        r = subprocess.run(['git', 'apply', '--whitespace=nowarn', '-p1', str(patch)], cwd=stage, env=env)
        if r.returncode != 0:
            raise SystemExit(f'patch failed: {patch.name}; existing overlay kept; candidate left at {stage}')
    if a.dest.exists():
        shutil.rmtree(a.dest)
    stage.rename(a.dest)
    (a.dest / STAMP).write_text(k + '\n', encoding='utf-8')
    print(f'iw4L overlay ready at {a.dest} ({commit[:12]}, {len(CRATES)} crates, {len(patches)} patches)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
